"""Run the contributor check suite and write its Markdown report."""
from __future__ import annotations

from datetime import datetime, timezone
import os
from pathlib import Path
import re
import shlex
import subprocess
import sys
import time

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "docs" / "TEST_REPORT.md"
CHECKS = [
    ["cargo", "fmt", "--check"],
    ["cargo", "clippy", "--locked", "--all-targets", "--", "-D", "warnings"],
    ["cargo", "test", "--locked"],
    ["node", "--check", "static/app.js"],
    ["node", "--test", "--test-reporter=tap"],
    ["cargo", "build", "--release", "--locked"],
]


def git_value(*args: str) -> str:
    try:
        return subprocess.check_output(
            ["git", *args], cwd=ROOT, text=True, stderr=subprocess.DEVNULL
        ).strip()
    except (OSError, subprocess.CalledProcessError):
        return "unavailable"


def discover_test_cases(command: list[str], output: str) -> list[tuple[str, str]]:
    if command[:2] == ["cargo", "test"]:
        states = re.findall(r"(?m)^test (.+) \.\.\. (ok|FAILED|ignored)$", output)
        return [
            (name, {"ok": "PASS", "FAILED": "FAIL", "ignored": "SKIP"}[state])
            for name, state in states
        ]

    if command[:2] == ["node", "--test"]:
        results = re.findall(
            r"(?m)^\s*(ok|not ok) \d+ - (.*?)(?:\s+#\s+(SKIP|TODO)\b.*)?$",
            output,
        )
        return [
            (name, annotation or ("PASS" if state == "ok" else "FAIL"))
            for state, name, annotation in results
        ]

    return []


def write_report(
    results: list[tuple[list[str], str, float, list[tuple[str, str]]]],
) -> str:
    passed = all(status == "PASS" for _, status, _, _ in results)
    timestamp = datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")
    branch = git_value("branch", "--show-current") or "detached HEAD"
    revision = git_value("rev-parse", "HEAD")
    overall = "PASSED" if passed else "FAILED"

    lines = [
        "# Test suite report",
        "",
        f"**Overall result: {overall}**",
        "",
        f"- Run time (UTC): {timestamp}",
        f"- Git revision at run time: `{revision}`",
        f"- Branch: `{branch}`",
        f"- Runner: `{sys.platform}`",
        "- Scope: current working tree",
        "",
        "| Check | Result | Duration |",
        "| --- | --- | ---: |",
    ]
    for command, status, duration, _ in results:
        lines.append(
            f"| `{shlex.join(command)}` | **{status}** | {duration:.1f}s |"
        )
    cases = [
        ("Rust" if command[:2] == ["cargo", "test"] else "Node", name, status)
        for command, _, _, test_cases in results
        for name, status in test_cases
    ]
    lines.extend([
        "",
        "## Discovered test cases",
        "",
        "| Suite | Test case | Result |",
        "| --- | --- | --- |",
    ])
    for suite, name, status in cases:
        markdown_name = name.replace("|", "\\|")
        lines.append(f"| {suite} | {markdown_name} | **{status}** |")
    if not cases:
        lines.append("| — | No test cases were reported by the suite commands. | — |")
    lines.extend([
        "",
        "Generated by [`scripts/run_checks.py`](../scripts/run_checks.py). "
        "GitHub Actions publishes this report for each pull request revision; "
        "use that current report as the test record during review.",
        "",
    ])
    report = "\n".join(lines)
    REPORT.write_text(report, encoding="utf-8")

    summary_path = os.environ.get("GITHUB_STEP_SUMMARY")
    if summary_path:
        with Path(summary_path).open("a", encoding="utf-8", newline="\n") as summary:
            summary.write(report)
            summary.write("\n")
    return overall


def main() -> int:
    results: list[tuple[list[str], str, float, list[tuple[str, str]]]] = []
    for index, command in enumerate(CHECKS, start=1):
        print(f"\n== Check {index}/{len(CHECKS)}: {shlex.join(command)} ==", flush=True)
        started = time.monotonic()
        try:
            process = subprocess.Popen(
                command,
                cwd=ROOT,
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                text=True,
                encoding="utf-8",
                errors="replace",
                bufsize=1,
            )
            assert process.stdout is not None
            output_lines = []
            for line in process.stdout:
                sys.stdout.write(line)
                sys.stdout.flush()
                output_lines.append(line)
            exit_code = process.wait()
            output = "".join(output_lines)
        except OSError as error:
            print(f"Could not start check: {error}", file=sys.stderr, flush=True)
            exit_code = 127
            output = ""
        duration = time.monotonic() - started
        status = "PASS" if exit_code == 0 else "FAIL"
        results.append((command, status, duration, discover_test_cases(command, output)))
        print(f"== {status} ({duration:.1f}s) ==", flush=True)

    overall = write_report(results)
    print(f"\nWrote {REPORT.relative_to(ROOT)}: {overall}", flush=True)
    return 0 if overall == "PASSED" else 1


if __name__ == "__main__":
    raise SystemExit(main())
